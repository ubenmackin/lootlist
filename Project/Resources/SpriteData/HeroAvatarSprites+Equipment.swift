        let size = 64
        var grid = Array(
            repeating: Array(repeating: Character("."), count: size),
            count: size
        )

        let corners = [(6, 6), (6, 58), (58, 6), (58, 58)]
        let rings: [(radius: Int, char: Character)] = [
            (4, "c"), // inner ring — light cyan
            (7, "C"), // middle ring — dark cyan
            (10, "c") // outer ring — light cyan
        ]

        // Draw main ring arcs
        for (cr, cc) in corners {
            for (ringRadius, ringChar) in rings {
                let lo = max(0, cr - ringRadius)
                let hi = min(size - 1, cr + ringRadius)
                for row in lo ... hi {
                    let dy = row - cr
                    let val = ringRadius * ringRadius - dy * dy
                    guard val >= 0 else { continue }
                    let dx = Int(round(sqrt(Double(val))))
                    for col in [cc - dx, cc + dx] {
                        if col >= 0, col < size {
                            grid[row][col] = ringChar
                        }
                    }
                }
            }
        }

        // Checkerboard dithering between ring layers (radii 5–6, 8–9)
        let ditherRadii = [5, 6, 8, 9]
        for (cr, cc) in corners {
            for ditherRadius in ditherRadii {
                let lo = max(0, cr - ditherRadius)
                let hi = min(size - 1, cr + ditherRadius)
                for row in lo ... hi {
                    let dy = row - cr
                    let val = ditherRadius * ditherRadius - dy * dy
                    guard val >= 0 else { continue }
                    let dx = Int(round(sqrt(Double(val))))
                    for col in [cc - dx, cc + dx] {
                        if col >= 0, col < size, grid[row][col] == "." {
                            grid[row][col] = (row + col) % 2 == 0 ? "c" : "C"
                        }
                    }
                }
            }
        }

        return grid.map { String($0) }
    }

    /// Generates a 64×64 matrix of gold star sparkle clusters, one near each canvas corner.
    /// Each cluster has a 5px cross and a 3px cross offset by (3,3), with scattered sparkle dots.
    private static func generateSparklesMatrix() -> [String] {
        let size = 64
        var grid = Array(
            repeating: Array(repeating: Character("."), count: size),
            count: size
        )

        let corners = [(5, 5), (5, 59), (59, 5), (59, 59)]

        func place(_ ch: Character, _ row: Int, _ col: Int) {
            if row >= 0, row < size, col >= 0, col < size {
                grid[row][col] = ch
            }
        }

        for (cr, cc) in corners {
            // 5px cross — center "Y", 2px arms "y"
            place("Y", cr, cc)
            for armDist in [1, 2] {
                place("y", cr - armDist, cc)
                place("y", cr + armDist, cc)
                place("y", cr, cc - armDist)
                place("y", cr, cc + armDist)
            }

            // 3px cross offset by (3, 3) from cluster center
            let sr = cr + 3, sc = cc + 3
            place("Y", sr, sc)
            place("y", sr - 1, sc)
            place("y", sr + 1, sc)
            place("y", sr, sc - 1)
            place("y", sr, sc + 1)

            // Scatter sparkle dots within 3px of cluster center
            let scatterOffsets = [(1, -2), (-2, 1), (2, 2), (-1, -3)]
            for (dr, dc) in scatterOffsets {
                let scatterRow = cr + dr, scatterCol = cc + dc
                if scatterRow >= 0, scatterRow < size, scatterCol >= 0, scatterCol < size,
                   grid[scatterRow][scatterCol] == "."
                {
                    grid[scatterRow][scatterCol] = "y"
                }
            }
        }

        return grid.map { String($0) }
    }

