    static func backgroundEquipmentLayer(for gearKey: String) -> PixelLayer? {
        if gearKey.contains("wing") {
            return goldenWingsLayer
        } else if gearKey.contains("shadow_cloak") || gearKey == "cloak" {
            return shadowCloakLayer
        } else if gearKey.contains("aura") || gearKey.contains("cosmic") {
            return cosmicAuraBackgroundLayer
        } else if gearKey.contains("bolt") || gearKey.contains("level.10") {
            return lightningSparksBackgroundLayer
        }
        return nil
    }

    static func foregroundEquipmentLayer(for gearKey: String) -> PixelLayer? {
        if gearKey.contains("crown") {
            return crownLayer
        } else if gearKey.contains("wizard_hat") || gearKey.contains("hat") {
            return wizardHatLayer
        } else if gearKey.contains("flaming_sword") || gearKey.contains("fire") || gearKey.contains("level.20") {
            return flamingSwordLayer
        } else if gearKey.contains("crystal_staff") || gearKey.contains("staff") {
            return crystalStaffLayer
        } else if gearKey.contains("sparkles") || gearKey.contains("level.5") {
            return sparklesLayer
        } else if gearKey.contains("star") || gearKey.contains("level.15") {
            return starAuraLayer
        } else if gearKey.contains("aura") || gearKey.contains("cosmic") {
            return cosmicAuraForegroundLayer
        }
        return nil
    }

